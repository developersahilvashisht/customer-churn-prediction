"""
Customer Churn Prediction API
==============================
FastAPI service that loads the trained Decision Tree pipeline and serves
churn predictions for new customers.

Run locally:
    uvicorn app:app --reload --port 8000

Then POST customer JSON to:
    http://127.0.0.1:8000/predict

Interactive docs (auto-generated by FastAPI) available at:
    http://127.0.0.1:8000/docs
"""
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field, field_validator
import pandas as pd
import joblib
import json
import os

from feature_engineering import engineer_features

MODEL_PATH = os.path.join("model", "churn_model.pkl")
METADATA_PATH = os.path.join("model", "metadata.json")

app = FastAPI(
    title="Customer Churn Prediction API",
    description="Predicts whether a telecom customer is likely to churn.",
    version="1.0.0",
)

# ---- Load model & metadata once, at startup
model_pipeline = None
metadata = None


@app.on_event("startup")
def load_artifacts():
    global model_pipeline, metadata
    if not os.path.exists(MODEL_PATH):
        raise RuntimeError(f"Model file not found at {MODEL_PATH}. Run build_pipeline.py first.")
    model_pipeline = joblib.load(MODEL_PATH)
    with open(METADATA_PATH) as f:
        metadata = json.load(f)


class CustomerData(BaseModel):
    gender: str = Field(..., examples=["Female"])
    SeniorCitizen: str = Field(..., description="'Yes' or 'No'", examples=["No"])
    Partner: str = Field(..., examples=["Yes"])
    Dependents: str = Field(..., examples=["No"])
    tenure: int = Field(..., ge=0, le=100, examples=[12])
    PhoneService: str = Field(..., examples=["Yes"])
    MultipleLines: str = Field(..., examples=["No"])
    InternetService: str = Field(..., examples=["Fiber optic"])
    OnlineSecurity: str = Field(..., examples=["No"])
    OnlineBackup: str = Field(..., examples=["Yes"])
    DeviceProtection: str = Field(..., examples=["No"])
    TechSupport: str = Field(..., examples=["No"])
    StreamingTV: str = Field(..., examples=["Yes"])
    StreamingMovies: str = Field(..., examples=["No"])
    Contract: str = Field(..., examples=["Month-to-month"])
    PaperlessBilling: str = Field(..., examples=["Yes"])
    PaymentMethod: str = Field(..., examples=["Electronic check"])
    MonthlyCharges: float = Field(..., ge=0, examples=[70.35])
    TotalCharges: float = Field(..., ge=0, examples=[845.5])

    @field_validator("SeniorCitizen", "Partner", "Dependents", "PhoneService",
                      "PaperlessBilling")
    @classmethod
    def must_be_yes_no(cls, v, info):
        if v not in ("Yes", "No"):
            raise ValueError(f"{info.field_name} must be 'Yes' or 'No', got '{v}'")
        return v

    @field_validator("gender")
    @classmethod
    def valid_gender(cls, v):
        if v not in ("Male", "Female"):
            raise ValueError(f"gender must be 'Male' or 'Female', got '{v}'")
        return v

    @field_validator("InternetService")
    @classmethod
    def valid_internet(cls, v):
        allowed = {"DSL", "Fiber optic", "No"}
        if v not in allowed:
            raise ValueError(f"InternetService must be one of {allowed}, got '{v}'")
        return v

    @field_validator("Contract")
    @classmethod
    def valid_contract(cls, v):
        allowed = {"Month-to-month", "One year", "Two year"}
        if v not in allowed:
            raise ValueError(f"Contract must be one of {allowed}, got '{v}'")
        return v

    @field_validator("PaymentMethod")
    @classmethod
    def valid_payment(cls, v):
        allowed = {"Electronic check", "Mailed check", "Bank transfer (automatic)",
                   "Credit card (automatic)"}
        if v not in allowed:
            raise ValueError(f"PaymentMethod must be one of {allowed}, got '{v}'")
        return v


class PredictionResponse(BaseModel):
    prediction: str
    churn_probability: float


@app.get("/")
def root():
    return {
        "message": "Customer Churn Prediction API is running.",
        "endpoints": {"predict": "POST /predict", "health": "GET /health", "docs": "GET /docs"},
    }


@app.get("/health")
def health():
    return {
        "status": "ok" if model_pipeline is not None else "model not loaded",
        "model": metadata.get("final_model") if metadata else None,
    }


@app.post("/predict", response_model=PredictionResponse)
def predict(customer: CustomerData):
    if model_pipeline is None:
        raise HTTPException(status_code=503, detail="Model is not loaded yet.")

    try:
        raw_df = pd.DataFrame([customer.model_dump()])
        # Apply the SAME feature engineering used at training time
        featured_df = engineer_features(raw_df)

        proba = model_pipeline.predict_proba(featured_df)[0, 1]
        pred = "Yes" if proba >= 0.5 else "No"

        return PredictionResponse(prediction=pred, churn_probability=round(float(proba), 4))

    except Exception as e:
        # Catches malformed / unexpected input that slips past pydantic validation
        raise HTTPException(status_code=400, detail=f"Invalid input or processing error: {str(e)}")
